// Select and preview a nature photo
// ======================================

$("photo").addEventListener("change", event => {
  const file = event.target.files?.[0];

  if (!file) return;

  if (!file.type.startsWith("image/")) {
    $("analysisResult").textContent =
      "Please select a valid image.";
    return;
  }

  if (file.size > 10 * 1024 * 1024) {
    $("analysisResult").textContent =
      "Please choose an image smaller than 10 MB.";
    return;
  }

  selectedPhoto = file;

  if (photoUrl) URL.revokeObjectURL(photoUrl);
  photoUrl = URL.createObjectURL(file);

  const img = document.createElement("img");
  img.src = photoUrl;
  img.alt = "Selected nature photo";

  $("previewArea").replaceChildren(img);
  $("analyzeBtn").disabled = false;

  $("analysisResult").textContent =
    "Photo ready. Click Identify my discovery to run AI.";
});

// ======================================
// Load and run open image model
// ======================================

async function analyzePhoto() {
  if (!selectedPhoto || !photoUrl) return;

  const button = $("analyzeBtn");
  button.disabled = true;

  try {
    $("analysisResult").textContent =
      "Loading the open image model...";

    if (!imageAI) {
      try {
        imageAI = await pipeline(
          "image-classification",
          IMAGE_MODEL,
          { device: "webgpu" }
        );
      } catch (error) {
        console.warn("Using CPU/WASM for image AI.", error);

        imageAI = await pipeline(
          "image-classification",
          IMAGE_MODEL,
          { device: "wasm" }
        );
      }
    }

    button.textContent = "Analyzing photo...";

    // The model processes the selected photo in the browser.
    const predictions = await imageAI(photoUrl, {
      top_k: 5
    });

    const heading = document.createElement("strong");
    heading.textContent = "AI predictions";

    const list = document.createElement("ol");
    list.style.paddingLeft = "20px";

    for (const item of predictions) {
      const li = document.createElement("li");

      li.textContent =
        `${item.label.replaceAll("_", " ")} — ` +
        `${(item.score * 100).toFixed(1)}%`;

      list.append(li);
    }

    const note = document.createElement("p");
    note.textContent =
      "General image predictions only. These are not verified " +
      "plant or species identifications. Never eat a wild plant " +
      "based on an AI result.";

    $("analysisResult").replaceChildren(heading, list, note);
  } catch (error) {
    console.error("Image AI error:", error);

    $("analysisResult").textContent =
      "Could not load the image model. Check your internet " +
      "connection, then try again.";
  } finally {
    button.disabled = !selectedPhoto;
    button.textContent = "Identify my discovery";
  }
}

$("analyzeBtn").addEventListener("click", analyzePhoto);

