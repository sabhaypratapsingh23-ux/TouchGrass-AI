// ======================================
// Load text AI directly in the browser
// ======================================

async function loadTextAI() {
  if (textAI) return textAI;

  status("Downloading the open AI model. This may take a while...");

  try {
    textAI = await pipeline(
      "text-generation",
      TEXT_MODEL,
      {
        dtype: "q4",
        device: "webgpu"
      }
    );
  } catch (gpuError) {
    console.warn("WebGPU unavailable; trying CPU/WASM.", gpuError);

    // Retry with the default CPU/WASM execution.
    textAI = await pipeline(
      "text-generation",
      TEXT_MODEL,
      {
        dtype: "q4",
        device: "wasm"
      }
    );
  }

  return textAI;
}

// ======================================
// Generate a real AI outdoor adventure
// ======================================

function displayQuest(quest, duration, aiGenerated) {
  currentQuest = {
    ...quest,
    duration: Number(duration),
    points: Math.max(10, Number(duration) * 2)
  };

  questCompleted = false;

  $("quest-type").textContent = aiGenerated
    ? "AI-GENERATED QUEST"
    : "NATURE QUEST";

  $("quest-emoji").textContent = quest.emoji || "🌱";
  $("quest-title").textContent = quest.title;
  $("quest-description").textContent = quest.description;
  $("quest-time").textContent = duration;
  $("quest-points").textContent = currentQuest.points;

  $("completeBtn").textContent =
    `I did it! +${currentQuest.points} points ✓`;

  $("completeBtn").disabled = false;

  status(aiGenerated
    ? "Generated by an open-weight model on your device."
    : "Using a built-in quest while AI is unavailable."
  );
}

function parseQuest(output) {
  const generated = output[0]?.generated_text;

  let answer = "";

  if (typeof generated === "string") {
    answer = generated;
  } else if (Array.isArray(generated)) {
    answer = generated
      .filter(message => message.role === "assistant")
      .map(message => message.content)
      .join("\n");
  }

  // Remove optional Markdown code fences.
  answer = answer
    .replace(/```(?:json)?/gi, "")
    .trim();

  const start = answer.indexOf("{");
  const end = answer.lastIndexOf("}");

  if (start < 0 || end <= start) {
    throw new Error("The model did not return valid JSON.");
  }

  const quest = JSON.parse(answer.slice(start, end + 1));

  if (
    typeof quest.title !== "string" ||
    typeof quest.description !== "string"
  ) {
    throw new Error("The model returned an incomplete quest.");
  }

  return quest;
}

async function generateQuest() {
  const button = $("generateBtn");
  const mood = $("mood").value;
  const duration = $("duration").value;
  const place = $("place").value;

  button.disabled = true;
  button.textContent = "Loading AI...";

  try {
    const ai = await loadTextAI();

    button.textContent = "Creating your adventure...";

    const messages = [
      {
        role: "system",
        content:
          "You create safe, fun outdoor nature challenges. " +
          "Return only valid JSON with title, emoji and description. " +
          "Never suggest eating wild plants, approaching wildlife, " +
          "entering dangerous areas or buying equipment."
      },
      {
        role: "user",
        content:
          `Create one original outdoor quest. ` +
          `Mood: ${mood}. Time: ${duration} minutes. ` +
          `Location: ${place}. ` +
          `Make it achievable, safe and screen-free. ` +
          `Return JSON only.`
      }
    ];

    const output = await ai(messages, {
      max_new_tokens: 110,
      do_sample: true,
      temperature: 0.7
    });

    const quest = parseQuest(output);

    displayQuest(quest, duration, true);
  } catch (error) {
    console.error("Text AI error:", error);

    const options = quests[mood];
    const fallback = options[
      Math.floor(Math.random() * options.length)
    ];

    displayQuest(fallback, duration, false);

    status(
      "AI could not load. A built-in quest is shown instead. " +
      "Check your connection, browser support and console."
    );
  } finally {
    button.disabled = false;
    button.textContent = "✦ Generate my quest";
  }
}

$("generateBtn").addEventListener("click", generateQuest);

