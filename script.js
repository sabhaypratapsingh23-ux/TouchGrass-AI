$("completeBtn").addEventListener("click", () => {
  if (!currentQuest || questCompleted) return;

  questCompleted = true;

  stats.minutes += currentQuest.duration;
  stats.points += currentQuest.points;
  stats.completed += 1;

  saveData();
  renderStats();

  $("completeBtn").disabled = true;
  $("completeBtn").textContent = "Quest completed ✓";

  status("Amazing! You made time for the real world. 🌿");
});

